import { chromium, expect } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { humanAPI } from '../../tests/s1/api.mjs';
import type { components } from '../src/api/schema';

type S = components['schemas'];
const origin = process.env.ASTROCYTE_TEST_PRODUCT_URL;
const source = process.env.ASTROCYTE_TEST_PRODUCT_SOURCE;
const output = process.env.ASTROCYTE_VERIFICATION_OUTPUT_DIR;
if (origin !== 'http://127.0.0.1:64505' || !source || !output) throw new Error('需要同一产品实际SOURCE和原公开候选记录目录');
const directory = resolve(output);
const original = JSON.parse(await readFile(resolve(directory, 'product-candidate-readonly.json'), 'utf8')) as {
  material_id: string; candidate_id: string; topic_id: string; revision: number; version: number; goal_refs: string[];
};
const path = resolve(directory, 'product-project-layer-human.json');
const evidence: { source: string; stage: string; started_at: string; completed_at?: string; distillation_id?: string;
  operations: { operation_id: string; path: string; status?: number }[]; events: { id: string; type: string; aggregate_id: string }[];
  stages?: string[]; candidate_unchanged?: boolean; new_model_turns: number } = {
  source, stage: 'started', started_at: new Date().toISOString(), operations: [], events: [], new_model_turns: 0,
};
await writeFile(path, JSON.stringify(evidence, null, 2), { flag: 'wx' });
const save = () => writeFile(path, JSON.stringify(evidence, null, 2));
const browser = await chromium.launch();
const database = new DatabaseSync('D:/Astrocyte-agent-assets/20261015/relay/H/shared-product-ad8413/local/astrocyte-workbench/v0.2-access/app-state/state.sqlite', { readOnly: true });
try {
  const api = await humanAPI(origin);
  const before = await api.get(`/materials/${original.material_id}`) as S['MaterialDetailV1'];
  const excerpt = before.distillations.find(item => item.id === 'LD6A7RPZQJIQW6F224QALLQDR5');
  if (!excerpt) throw new Error('原已保存人工摘要不存在，禁止生成替代正文');
  expect(before.distillations.map(item => item.stage).sort()).toEqual(['content', 'topic']);
  expect(original.goal_refs).toHaveLength(1);
  const { goal } = await api.get(`/goals/${original.goal_refs[0]}`) as S['S2GoalResultV1'];
  const candidate = await api.get(`/opportunities/${original.candidate_id}`) as S['OpportunityDetailV1'];
  expect(candidate.opportunity).toMatchObject({ revision: original.revision, version: original.version, state: 'ready_for_review' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/v1/') && request.method() !== 'GET') evidence.operations.push({ operation_id: request.headers()['idempotency-key'] ?? '', path: new URL(request.url()).pathname }); });
  await page.goto(`${origin}/attention`);
  await page.locator('main li[role="button"]').filter({ has: page.getByText(before.material.title!, { exact: true }) }).click();
  const dialog = page.getByRole('dialog', { name: '素材详情', exact: true });
  await dialog.getByRole('button', { name: '继续沉淀', exact: true }).click();
  const form = dialog.locator('form').filter({ has: page.getByRole('button', { name: '保存人工沉淀', exact: true }) });
  await form.getByLabel('沉淀层次', { exact: true }).selectOption('project');
  const question = '公开摘要的项目关联：固定来源与现有目标的人工核查';
  await form.getByLabel('本轮问题', { exact: true }).fill(question);
  await form.getByLabel('人工整理结果', { exact: true }).fill(excerpt.output_text);
  await form.getByLabel('待查问题（每行一项）', { exact: true }).fill('当前论文在本项目的实际收益和原生执行仍未验证。');
  await form.getByLabel('关联目标（每行一项）', { exact: true }).fill(goal.id);
  const assets = [`固定资料 ${original.material_id}@1`, `主题记录 ${original.topic_id}`, `候选 ${original.candidate_id}@${original.revision}`];
  await form.getByLabel('现有资产（每行一项）', { exact: true }).fill(assets.join('\n'));
  await form.getByLabel('预期改进', { exact: true }).fill('让项目关联记录可追溯到现有固定资料和目标，保留未完成的效果核查。');
  await form.getByLabel('最小成果', { exact: true }).fill('已保存公开论文固定版本、主题待查问题、候选和人工反馈的核查记录。');
  await form.getByLabel('缺失依据（每行一项）', { exact: true }).fill('尚无新的模型或原生执行结果。');
  evidence.stage = 'saving_project_layer'; await save();
  const saving = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/distillations' && response.request().method() === 'POST');
  await form.getByRole('button', { name: '保存人工沉淀', exact: true }).click();
  const response = await saving;
  expect(evidence.operations).toHaveLength(1);
  evidence.operations[0].status = response.status(); await save();
  expect(response.status()).toBe(200);
  const { distillation } = await response.json() as S['DistillationResultV1'];
  evidence.distillation_id = distillation.id; await save();
  expect(distillation).toMatchObject({ stage: 'project', question, goal_refs: [goal.id], existing_assets: assets, provenance: { processor: 'human', mode: 'manual' } });
  expect(distillation.output_text).toBe(excerpt.output_text.trim());
  expect(distillation.input_refs.map(item => ({ material_id: item.material_id, revision: item.revision }))).toEqual([{ material_id: original.material_id, revision: 1 }]);
  const detail = await api.get(`/materials/${original.material_id}`) as S['MaterialDetailV1'];
  evidence.stages = detail.distillations.map(item => item.stage).sort();
  expect(evidence.stages).toEqual(['content', 'project', 'topic']);
  const record = database.prepare('SELECT data FROM attention_distillations WHERE id=?').get(distillation.id) as { data: string };
  expect(JSON.parse(record.data)).toEqual(distillation);
  evidence.events = database.prepare('SELECT id,type,aggregate_id FROM attention_outbox WHERE correlation_id=?').all(evidence.operations[0].operation_id) as typeof evidence.events;
  expect(evidence.events).toHaveLength(1);
  expect(evidence.events[0]).toMatchObject({ type: 'attention.distillation_recorded', aggregate_id: distillation.id });
  for (const event of evidence.events) expect(database.prepare('SELECT id,type,aggregate_id FROM attention_outbox WHERE id=?').get(event.id)).toEqual(event);
  expect((await api.get(`/opportunities/${original.candidate_id}`) as S['OpportunityDetailV1'])).toEqual(candidate);
  expect(database.prepare('SELECT COUNT(*) AS count FROM local_agent_sessions').get()).toEqual({ count: 0 });
  await expect(dialog.getByRole('article').filter({ hasText: question })).toContainText(goal.id);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  Object.assign(evidence, { stage: 'three_manual_layers_completed', candidate_unchanged: true, completed_at: new Date().toISOString() });
  await save(); console.log(JSON.stringify(evidence));
} finally { await save(); await browser.close(); database.close(); }
