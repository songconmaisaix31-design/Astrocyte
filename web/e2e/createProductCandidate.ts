import { chromium, expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { humanAPI } from '../../tests/s1/api.mjs';
import type { components } from '../src/api/schema';

type S = components['schemas'];
const origin = process.env.ASTROCYTE_TEST_PRODUCT_URL;
const source = process.env.ASTROCYTE_TEST_PRODUCT_SOURCE;
const records = process.env.ASTROCYTE_TEST_PRODUCT_RECORDS_DIR;
const output = process.env.ASTROCYTE_VERIFICATION_OUTPUT_DIR;
if (origin !== 'http://127.0.0.1:64505' || !source || !/^[0-9a-f]{40}$/.test(source) || !records || !output || resolve(records) === resolve(output)) throw new Error('需要获准同实例SOURCE、原公开记录与独立输出目录');
const paper = JSON.parse(await readFile(resolve(records, 'product-paper-readonly.json'), 'utf8')) as { material_ids: string[]; manual_distillation_id: string };
const originalProposal = JSON.parse(await readFile(resolve(records, 'product-proposal-human.json'), 'utf8')) as { goal_id: string; project_id: string };
const directory = resolve(output);
await mkdir(directory, { recursive: true });
const path = resolve(directory, 'product-candidate-human.json');
const evidence: {
  source: string; stage: string; started_at: string; completed_at?: string; material_id: string; original_excerpt_id: string;
  topic_id?: string; candidate_id?: string; revision?: number; state?: string;
  operations: { method: string; path: string; operation_id: string; status?: number }[];
  events: { id: string; type: string; aggregate_id: string }[]; native_sessions?: number;
} = { source, stage: 'started', started_at: new Date().toISOString(), material_id: paper.material_ids[1], original_excerpt_id: paper.manual_distillation_id, operations: [], events: [] };
// 一次窗口只建立一次记录；已存在的结果需先只读恢复，不能直接重跑本脚本。
await writeFile(path, JSON.stringify(evidence, null, 2), { flag: 'wx' });
const save = () => writeFile(path, JSON.stringify(evidence, null, 2));
const database = new DatabaseSync('D:/Astrocyte-agent-assets/20261015/relay/H/shared-product-ad8413/local/astrocyte-workbench/v0.2-access/app-state/state.sqlite', { readOnly: true });
const browser = await chromium.launch();
try {
  const api = await humanAPI(origin);
  const detail = await api.get(`/materials/${evidence.material_id}`) as S['MaterialDetailV1'];
  expect(detail.material.current_revision).toBe(1);
  const excerpt = detail.distillations.find(item => item.id === paper.manual_distillation_id);
  expect(excerpt?.provenance).toMatchObject({ processor: 'human', mode: 'manual' });
  if (!excerpt?.output_text.trim()) throw new Error('原已保存公开摘要不存在，禁止生成替代正文');
  const question = '公开论文摘要的主题关联：固定来源和未完成的实际效果核查';
  expect(detail.distillations.some(item => item.question === question)).toBe(false);
  expect((await api.get('/opportunities') as S['OpportunityListV1']).items).toEqual([]);
  const beforeEvents = new Set((database.prepare('SELECT id FROM attention_outbox').all() as { id: string }[]).map(item => item.id));
  const approvalCount = database.prepare('SELECT COUNT(*) AS count FROM workspace_approvals').get();
  const missionCount = database.prepare('SELECT COUNT(*) AS count FROM swarm_missions').get();
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  page.on('request', request => {
    if (new URL(request.url()).pathname.startsWith('/api/v1/') && request.method() !== 'GET') evidence.operations.push({ method: request.method(), path: new URL(request.url()).pathname, operation_id: request.headers()['idempotency-key'] ?? '' });
  });
  page.on('response', response => {
    const operation = evidence.operations.find(item => item.operation_id === response.request().headers()['idempotency-key']);
    if (operation) operation.status = response.status();
  });
  await page.goto(`${origin}/attention`);
  await page.locator('main li[role="button"]').filter({ has: page.getByText(detail.material.title!, { exact: true }) }).click();
  let dialog = page.getByRole('dialog', { name: '素材详情', exact: true });
  await dialog.getByRole('button', { name: '继续沉淀', exact: true }).click();
  const topicForm = dialog.locator('form').filter({ has: page.getByRole('button', { name: '保存人工沉淀', exact: true }) });
  await topicForm.getByLabel('沉淀层次', { exact: true }).selectOption('topic');
  await topicForm.getByLabel('本轮问题', { exact: true }).fill(question);
  await topicForm.getByLabel('人工整理结果', { exact: true }).fill(excerpt.output_text);
  await topicForm.getByLabel('待查问题（每行一项）', { exact: true }).fill('当前公开摘要与本项目的实际改进之间仍缺少任务结果和独立效果证据。');
  evidence.stage = 'saving_new_topic'; await save();
  const topicResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/distillations' && response.request().method() === 'POST');
  await topicForm.getByRole('button', { name: '保存人工沉淀', exact: true }).click();
  const topicHTTP = await topicResponse;
  expect(topicHTTP.status()).toBe(200);
  const { distillation: topic } = await topicHTTP.json() as S['DistillationResultV1'];
  evidence.topic_id = topic.id; await save();
  expect(topic.id).not.toBe(excerpt.id);
  expect(topic.output_text).toBe(excerpt.output_text.trim());
  expect(topic.provenance).toMatchObject({ processor: 'human', mode: 'manual' });
  expect(topic.input_refs.map(item => ({ material_id: item.material_id, revision: item.revision }))).toEqual([{ material_id: evidence.material_id, revision: 1 }]);
  await dialog.getByRole('button', { name: '形成候选', exact: true }).click();
  const form = dialog.locator('form').filter({ has: page.getByRole('button', { name: '保存候选', exact: true }) });
  await form.getByLabel('候选标题', { exact: true }).fill('公开论文固定摘要的候选复核');
  await form.getByLabel('候选用途 / 为什么值得做', { exact: true }).fill('保留当前公开摘要及固定版本，在人工审阅后核查资料与本项目的实际适用性。');
  await form.getByLabel('最小下一步', { exact: true }).fill('先核对固定摘要和待查问题，再由人工分别决定资料准入与任务批准。');
  await form.getByLabel('缺失依据（每行一项）', { exact: true }).fill('实际任务结果和独立效果证据尚未产生。');
  await form.getByLabel('关联目标（每行一项）', { exact: true }).fill(originalProposal.goal_id);
  await form.getByRole('checkbox', { name: `topic · ${question} · ${topic.id}`, exact: true }).check();
  for (const label of ['目标进展', '当前兴趣', '项目改善', '创新性']) {
    await expect(form.getByLabel(`${label}（0–1，未知留空）`, { exact: true })).toHaveValue('');
    await form.getByLabel(`${label}依据`, { exact: true }).fill('尚未进行实际任务和效果评估。');
  }
  evidence.stage = 'creating_candidate'; await save();
  const creating = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/opportunities' && response.request().method() === 'POST');
  await form.getByRole('button', { name: '保存候选', exact: true }).click();
  const createdHTTP = await creating;
  expect(createdHTTP.status()).toBe(201);
  const created = await createdHTTP.json() as S['OpportunityDetailV1'];
  evidence.candidate_id = created.opportunity.id; evidence.revision = created.opportunity.revision; await save();
  expect(created.opportunity.state).toBe('ready_for_review');
  expect(created.opportunity.distillation_ids).toEqual([topic.id]);
  expect(Object.values(created.opportunity.dimensions).every(item => item.value === null)).toBe(true);
  dialog = page.getByRole('dialog', { name: '机会详情', exact: true });
  await dialog.getByLabel('反馈类型', { exact: true }).selectOption('later');
  await dialog.getByLabel('反馈理由', { exact: true }).fill('当前只保存公开来源候选，实际适用性和效果仍待后续核查。');
  evidence.stage = 'saving_human_later'; await save();
  const reviewing = page.waitForResponse(response => new URL(response.url()).pathname.endsWith(`/opportunities/${evidence.candidate_id}/reviews`) && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: '保存人工反馈', exact: true }).click();
  expect((await reviewing).status()).toBe(201);
  const deferred = await api.get(`/opportunities/${evidence.candidate_id}`) as S['OpportunityDetailV1'];
  expect(deferred.opportunity.state).toBe('deferred');
  expect(deferred.reviews).toHaveLength(1);
  expect(deferred.reviews[0]).toMatchObject({ revision: 1, feedback: 'later' });
  await expect(dialog.getByText('以后再做 · r1', { exact: false })).toBeVisible();
  await dialog.getByRole('button', { name: '编辑候选', exact: true }).click();
  const editing = dialog.locator('form').filter({ has: page.getByRole('button', { name: '保存候选新版本', exact: true }) });
  await editing.getByLabel('缺失依据（每行一项）', { exact: true }).fill('人工暂缓记录已保存；实际任务、模型处理与独立效果证据仍未产生。');
  evidence.stage = 'saving_candidate_revision'; await save();
  const revising = page.waitForResponse(response => new URL(response.url()).pathname.endsWith(`/opportunities/${evidence.candidate_id}/revisions`) && response.request().method() === 'POST');
  await editing.getByRole('button', { name: '保存候选新版本', exact: true }).click();
  const revisedHTTP = await revising;
  expect(revisedHTTP.status()).toBe(200);
  const revised = await revisedHTTP.json() as S['OpportunityDetailV1'];
  expect(revised.opportunity.revision).toBe(2);
  expect(revised.opportunity.state).toBe('ready_for_review');
  expect(revised.revisions).toHaveLength(2);
  expect(revised.revisions[0]).toEqual(created.revisions[0]);
  expect(revised.reviews).toEqual(deferred.reviews);
  expect(revised.opportunity.evidence_refs).toEqual(created.opportunity.evidence_refs);
  expect(revised.opportunity.dimensions).toEqual(created.opportunity.dimensions);
  evidence.events = (database.prepare('SELECT id,type,aggregate_id FROM attention_outbox').all() as typeof evidence.events).filter(event => !beforeEvents.has(event.id));
  expect(evidence.events.map(event => event.type).sort()).toEqual(['attention.distillation_recorded', 'attention.opportunity_created', 'attention.opportunity_reviewed', 'attention.opportunity_revised'].sort());
  for (const event of evidence.events) expect(database.prepare('SELECT id,type,aggregate_id FROM attention_outbox WHERE id=?').get(event.id)).toEqual(event);
  const saved = database.prepare('SELECT data FROM attention_opportunities WHERE id=?').get(evidence.candidate_id) as { data: string };
  expect(JSON.parse(saved.data)).toEqual(revised);
  expect(database.prepare('SELECT COUNT(*) AS count FROM workspace_approvals').get()).toEqual(approvalCount);
  expect(database.prepare('SELECT COUNT(*) AS count FROM swarm_missions').get()).toEqual(missionCount);
  expect(database.prepare('SELECT COUNT(*) AS count FROM local_agent_sessions').get()).toEqual({ count: 0 });
  expect(evidence.operations).toHaveLength(4);
  expect(evidence.operations.every(item => item.operation_id && item.status && item.status < 300)).toBe(true);
  expect(new Set(evidence.operations.map(item => item.operation_id)).size).toBe(4);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  Object.assign(evidence, { stage: 'candidate_feedback_completed', revision: revised.opportunity.revision, state: revised.opportunity.state, native_sessions: 0, completed_at: new Date().toISOString() });
  await save();
  console.log(JSON.stringify(evidence));
} finally { await save(); await browser.close(); database.close(); }
