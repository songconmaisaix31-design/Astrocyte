/// <reference types="node" />
import { chromium, expect } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type { components } from '../src/api/schema';

type S = components['schemas'];
const origin = process.env.ASTROCYTE_TEST_RELAY_PUBLIC_URL;
const taskID = process.env.ASTROCYTE_TEST_RELAY_CURRENT_TASK_ID;
const factsPath = process.env.ASTROCYTE_TEST_RELAY_RELEASE_FACTS_FILE;
if (!origin || !/^http:\/\/127\.0\.0\.1:\d+$/.test(origin) || !taskID || !factsPath) throw new Error('需要根批准的旧任务清理范围与H实际条件文件');
const facts = JSON.parse(await readFile(factsPath, 'utf8')) as { task_id: string; state: string; workspace_prepared: boolean; active_task_id: string; workspace_project_matches: boolean; terminal_workspace_matches: boolean; terminal_agent_matches: boolean; exited_at: string; pending_action: unknown; pending_receipts: number };
expect(facts.task_id).toBe(taskID);
expect(facts.state).toBe('done');
expect(facts.workspace_prepared).toBe(true);
expect(facts.active_task_id).toBe(taskID);
expect([facts.workspace_project_matches, facts.terminal_workspace_matches, facts.terminal_agent_matches]).toEqual([true, true, true]);
expect(facts.exited_at).toBeTruthy();
expect(facts.pending_action).toBeNull();
expect(facts.pending_receipts).toBe(0);
const path = resolve('../.verification/l1-live/existing-release-ui-safe.json');
const evidence: { task_id: string; authorization: string; goal_acceptance: string; source_identity_gate: string; stage: string; started_at: string; operation_id?: string; status?: number; receipt_status?: string; state?: string; active_task_id?: string; prepared?: boolean; completed_at?: string } = { task_id: taskID, authorization: 'root msg0957f72ac9ee and H msg_5e3fa7994376', goal_acceptance: 'failed_before_goal_check', source_identity_gate: 'failed_nlink2', stage: 'before_release', started_at: new Date().toISOString() };
await writeFile(path, JSON.stringify(evidence, null, 2), { flag: 'wx' });
const save = () => writeFile(path, JSON.stringify(evidence, null, 2));
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
  const page = await context.newPage();
  expect((await page.request.get(`${origin}/api/v1/auth/session`)).status()).toBe(200);
  const readTask = async () => {
    const response = await page.request.get(`${origin}/api/v1/relay/tasks/${taskID}`);
    expect(response.status()).toBe(200);
    return (await response.json() as S['RelayTaskResultV1']).view;
  };
  const before = await readTask();
  expect(before.task.state).toBe('done');
  expect(before.task.project_settings_revision).toBe(2);
  expect(before.terminal?.liveness).toBe('exited');
  expect(before.terminal?.exited_at).toBe(facts.exited_at);
  expect(before.worktree?.prepared).toBe(true);
  expect(before.worktree?.active_task_id).toBe(taskID);
  expect(before.worktree?.project_id).toBe(before.task.project_id);
  expect(before.terminal?.worktree_id).toBe(before.task.worktree_id);
  expect(before.terminal?.agent).toBe(before.task.agent);
  await page.goto(`${origin}/workspace/works`);
  await page.locator('.relay-tasks > li').filter({ hasText: taskID }).getByRole('button', { name: '查看任务、事件和收据', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const controls = dialog.getByRole('region', { name: '人工完成与交接' });
  await expect(dialog.getByRole('button', { name: '读取会话并留收据', exact: true })).toBeDisabled();
  await expect(dialog.getByRole('button', { name: '停止 Agent', exact: true })).toBeDisabled();
  await controls.getByRole('checkbox').check();
  const releasing = page.waitForResponse(response => response.url().endsWith(`/tasks/${taskID}/transition`) && response.request().method() === 'POST');
  await controls.getByRole('button', { name: '确认释放工作区', exact: true }).click();
  const response = await releasing;
  evidence.operation_id = response.request().headers()['idempotency-key'];
  evidence.status = response.status();
  evidence.stage = 'release_response_received';
  await save();
  expect(response.status()).toBe(200);
  const { view } = await response.json() as S['RelayTaskResultV1'];
  expect(view.task.state).toBe('released');
  const receiptsResponse = await page.request.get(`${origin}/api/v1/relay/tasks/${taskID}/receipts`);
  expect(receiptsResponse.status()).toBe(200);
  const { receipts } = await receiptsResponse.json() as S['RelayReceiptsV1'];
  const receipt = receipts.find(item => item.operation_id === evidence.operation_id);
  evidence.receipt_status = receipt?.status;
  await save();
  expect(receipt?.status).toBe('accepted');
  expect(receipts.find(item => item.operation_id === '5f99133e-390f-4987-b8f2-2889716921ff')?.status).toBe('delivery_unknown');
  const after = await readTask();
  Object.assign(evidence, { state: after.task.state, active_task_id: after.worktree?.active_task_id, prepared: after.worktree?.prepared });
  await save();
  expect(after.task.state).toBe('released');
  expect(after.worktree?.active_task_id).toBe('');
  expect(after.worktree?.prepared).toBe(true);
  await expect(dialog).toContainText('已释放 · released');
  Object.assign(evidence, { stage: 'released_observed', receipt_status: receipt!.status, state: after.task.state, active_task_id: after.worktree!.active_task_id, prepared: after.worktree!.prepared, completed_at: new Date().toISOString() });
  await save();
  console.log('F_CLEANUP_RELEASE_OBSERVED: 实际释放与空占用已保存，目标验收FAIL和原read未知保留。');
} catch (cause) {
  evidence.stage = `failed_${evidence.stage}`;
  await save();
  throw cause;
} finally { await browser.close(); }
